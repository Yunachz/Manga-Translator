export function copy(locale: UiLanguage) {
  return locale === 'id' ? id : en;
}

export function format(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (match, key: string) => Object.hasOwn(values, key) ? String(values[key]) : match);
}

const names: Record<UiLanguage, Intl.DisplayNames> = {
  en: new Intl.DisplayNames('en', { type: 'language' }),
  id: new Intl.DisplayNames('id', { type: 'language' }),
};

export function languageLabel(locale: UiLanguage, code: string): string {
  return code === 'auto' ? copy(locale).auto : names[locale].of(code) ?? code;
}
